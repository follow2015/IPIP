def _to_regex(tpl: str) -> re.Pattern:
    parts = re.split(r"\{(\w+)\}", tpl)
    out = []
    for i, seg in enumerate(parts):
        if i % 2 == 1:
            out.append('(?P<%s>.+?)' % seg)
        else:
            out.append(re.escape(seg))
    return re.compile(''.join(out) + '$')


_COMPILED: Optional[List[Tuple[re.Pattern, str, Tuple[str, ...]]]] = None


def _compile() -> List[Tuple[re.Pattern, str, Tuple[str, ...]]]:
    """惰性编译：模块导入时不做正则编译，避免拖慢冷启动"""
    global _COMPILED
    if _COMPILED is None:
        _COMPILED = [(_to_regex(tpl), key, params) for tpl, key, params in PATTERNS]
    return _COMPILED


def resolve_error_i18n(message):
    """
    把后端中文错误文案解析成前端可翻译的 (i18n_key, params)。

    Args:
        message: 异常 message（已渲染，插值已替换成实际值）

    Returns:
        (i18n_key, params) 命中；None 表示未收录（调用方应原样返回 message）
    """
    if not isinstance(message, str) or not message:
        return None
    key = LITERAL.get(message)
    if key is not None:
        return 'backend:' + key, {}
    for rx, key, params in _compile():
        m = rx.match(message)
        if m:
            return 'backend:' + key, {p: m.group(p) for p in params}
    return None
